function FormatCommas(arg: string)
    local prefix, numbers = arg:match("^(.-)(%d+)$")
    if not numbers then
        return
    end

    numbers = numbers:reverse():gsub("(%d%d%d)", "%1,"):reverse():gsub("^,", "")
    return prefix .. numbers
end

for rarityCategory, brainrots in pairs(BRAINROTS_DATA) do
    if rarityCategory == "SELL_FACTOR" then
		continue
	end

    for name, brainrot in pairs(brainrots) do
        BrainrotsData[name] = {
            RarityWeight = brainrot.RarityWeight,
            RarityType = tostring(rarityCategory),
            IdleAnimationID = brainrot.IdleAnimationID,
            CashPerSecond = FormatCommas(tostring(brainrot.MoneyPerSec)),
            SellPrice = math.floor(brainrot.MoneyPerSec * BRAINROTS_DATA.SELL_FACTOR),
            FractionChance = FormatCommas("1/" .. math.max(1, math.floor(100000000 / brainrot.RarityWeight * 2))),
            Timer = brainrot.Timer,
        }
    end
end

return {
    Original = BRAINROTS_DATA,
    Processed = BrainrotsData,
