function FormatCommas(arg: string)
    local prefix, numbers = arg:match("^(.-)(%d+)$")
    if not numbers then
        return
    end

    numbers = numbers:reverse():gsub("(%d%d%d)", "%1,"):reverse():gsub("^,", "")
    return prefix .. numbers
end

